// An inline-cache entry precedes the verified entry with the same frame state.
static unsigned checkUnverifiedEntry() {
    using namespace WindowsProfiler::JavaUnwind::Compiled;
    std::vector<unsigned char> code{
        0x48,0x3b,0x42,0x08,0x0f,0x85,0x00,0x10,0x00,0x00,0x66,0x0f,0x1f,0x44,0x00,0x00, // CMP; JNE miss; NOP
        0x48,0x83,0xec,0x38,0x90,0x48,0x83,0xc4,0x38,0xc3,                               // verified entry
        0xe8,0xe1,0xff,0xff,0xff,0x90,0x48,0x83,0xc4,0x38,0xc3                           // CALL 0, epilogue
    };
    Layout layout{reinterpret_cast<std::uintptr_t>(code.data()),0,0x10,0x38,true,true};
    std::vector<Span> spans;
    assert(analyse(code.data(),code.size(),layout,spans));
    assert(!at(spans,0).proven && at(spans,0x14).proven && at(spans,0x14).returnOffset == 0x38);
    layout.unverifiedEntry = 0;
    assert(analyse(code.data(),code.size(),layout,spans));
    for (auto pc : {0u,4u,0xau}) assert(at(spans,pc).proven && at(spans,pc).returnOffset == 0 && at(spans,pc).fpOffset == -1);
    assert(at(spans,0x14).proven && at(spans,0x14).returnOffset == 0x38);
    auto unchanged = spans;
    for (auto entry : {std::size_t{0x10},std::size_t{0x11}}) {
        auto invalid = layout; invalid.unverifiedEntry = entry;
        assert(!analyse(code.data(),code.size(),invalid,unchanged));
    }
    // A direct call may target either entry; other in-body targets stay rejected.
    auto calls = code;
    calls[0x14] = 0xe9;  // JMP 0x1a replaces NOP and the epilogue.
    std::int32_t skip = 0x1a - 0x19;
    std::memcpy(calls.data() + 0x15,&skip,4);
    auto direct = layout; direct.address = reinterpret_cast<std::uintptr_t>(calls.data());
    std::vector<Span> called;
    assert(analyse(calls.data(),calls.size(),direct,called));
    std::int32_t inside = 0x14 - 0x1f;
    std::memcpy(calls.data() + 0x1b,&inside,4);
    assert(!analyse(calls.data(),calls.size(),direct,called));
    auto checked = contexts(code,spans);
    std::printf("CFG_UNVERIFIED_ENTRY contexts=%u\n",checked);
    return checked;
}

