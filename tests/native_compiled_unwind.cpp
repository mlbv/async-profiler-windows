static const WindowsProfiler::JavaUnwind::Compiled::Span& at(const std::vector<WindowsProfiler::JavaUnwind::Compiled::Span>& spans,unsigned pc) {
    for (const auto& span : spans) if (pc >= span.begin && pc < span.end) return span;
    std::abort();
}
static std::uintptr_t callTarget(const std::vector<unsigned char>& code,unsigned pc) {
    assert(code[pc] == 0xe8);
    std::int32_t displacement;
    std::memcpy(&displacement,code.data() + pc + 1,4);
    return reinterpret_cast<std::uintptr_t>(code.data()) + pc + 5 + displacement;
}
