#include "windowsCompiledUnwind.h"
#include <windows.h>
#include <cassert>
#include <cstdio>
#include <cstring>
#include <cstdlib>

using namespace WindowsProfiler::JavaUnwind::Compiled;
namespace {
unsigned checks;
const Span& at(const std::vector<Span>& spans,unsigned pc) {
    for (const auto& span : spans) if (span.begin <= pc && pc < span.end) return span;
    std::abort();
}
struct Observed { DWORD64 original, rbp, slot; };
// Overwrites the saved slot through `alias`, then records the actual RBP and slot.
void executed(std::initializer_list<unsigned char> alias) {
    std::vector<unsigned char> code{
        0x48,0x89,0x29,                   // Save the caller RBP outside the analysed entry.
        0x48,0x83,0xec,0x38,
        0x48,0x89,0x6c,0x24,0x30,
        0x48,0x31,0xed};
    code.insert(code.end(),alias);
    auto sampled = static_cast<unsigned>(code.size());
    code.insert(code.end(),{
        0x90,
        0x48,0x89,0x69,0x08,              // Retain actual RBP and overwritten bytes.
        0x48,0x8b,0x44,0x24,0x30,
        0x48,0x89,0x41,0x10,
        0x48,0x8b,0x29,                   // Restore the ABI from the independent observation.
        0x48,0x83,0xc4,0x38,0xc3});
    Layout layout{reinterpret_cast<std::uintptr_t>(code.data()),0,3,56,true,true};
    std::vector<Span> spans;
    assert(analyse(code.data(),code.size(),layout,spans));
    const auto& rule = at(spans,sampled);
    auto memory = static_cast<unsigned char*>(VirtualAlloc(nullptr,4096,MEM_RESERVE|MEM_COMMIT,PAGE_READWRITE));
    assert(memory);
    std::memcpy(memory,code.data(),code.size());
    DWORD previous;
    assert(VirtualProtect(memory,4096,PAGE_EXECUTE_READ,&previous));
    assert(FlushInstructionCache(GetCurrentProcess(),memory,code.size()));
    Observed observed{};
    reinterpret_cast<void (*)(Observed*)>(memory)(&observed);
    assert(observed.rbp == 0 && observed.slot == reinterpret_cast<DWORD64>(&observed));
    assert(observed.original != observed.slot);
    assert(!rule.proven);
    assert(VirtualFree(memory,0,MEM_RELEASE));
    ++checks;
}
void effects(std::initializer_list<unsigned char> instruction,bool slotRetained,bool live = false) {
    std::vector<unsigned char> code{0x48,0x83,0xec,0x38,0x48,0x89,0x6c,0x24,0x30};
    if (!live) code.insert(code.end(),{0x48,0x31,0xed});
    code.insert(code.end(),instruction);
    auto sampled = static_cast<unsigned>(code.size());
    code.push_back(0x90);
    if (live) code.insert(code.end(),{0x48,0x31,0xed,0x90});
    code.insert(code.end(),{0x0f,0x0b});
    Layout layout{reinterpret_cast<std::uintptr_t>(code.data()),0,0,56,true,true};
    std::vector<Span> spans;
    assert(analyse(code.data(),code.size(),layout,spans));
    const auto& rule = at(spans,sampled);
    assert(rule.proven == (slotRetained || live));
    if (rule.proven) assert(rule.returnOffset == 56 && rule.fpOffset == (live ? -1 : 48));
    if (live) assert(at(spans,sampled + 4).proven == slotRetained);
    ++checks;
}
}
int main() {
    executed({0xb8,0x30,0,0,0,0x48,0x89,0x0c,0x04});           // Indexed RSP store.
    executed({0x48,0x8d,0x44,0x24,0x20,0x48,0x89,0x48,0x10});  // Pointer derived from RSP.
    // Stores not based on RSP cannot write the saved slot.
    for (auto bytes : {std::initializer_list<unsigned char>{0x48,0x89,0x08},
            {0x89,0x08},{0x66,0x89,0x08},{0x49,0x89,0x0c,0x24},{0x48,0x89,0x4d,0x00},
            {0x48,0x01,0x08},{0x48,0x09,0x08},{0x48,0x21,0x08},{0x48,0x29,0x08},{0x48,0x31,0x08},
            {0x48,0xc1,0x20,1},{0x48,0xff,0x00},{0x48,0xff,0x08},
            {0x48,0xc7,0x00,1,0,0,0},{0x48,0x81,0x00,1,0,0,0},{0x48,0x83,0x00,1},
            {0xf0,0x48,0x01,0x08},{0x48,0x89,0x0d,0,0,0,0},{0xf0,0x48,0x0f,0xb1,0x08}}) {
        effects(bytes,true);
    }
    effects({0x48,0x89,0x4c,0x04,0x28},false); // RSP plus an index may reach the slot.
    effects({0x48,0x89,0x4c,0x24,0x28},true);  // Ends exactly below the saved slot.
    effects({0x89,0x4c,0x24,0x2c},true);
    effects({0x66,0x89,0x4c,0x24,0x2e},true);
    effects({0x48,0x89,0x4c,0x24,0x29},false); // Partial overlap.
    effects({0x89,0x4c,0x24,0x2d},false);
    effects({0x66,0x89,0x4c,0x24,0x2f},false);
    effects({0x48,0x89,0x4c,0x24,0x30},false);
    effects({0x48,0x89,0x4c,0x24,0x38},true);
    effects({0x48,0x89,0x08},true,true);         // A live incoming RBP remains usable until clobbered.
    effects({0x48,0x89,0x4c,0x04,0x28},false,true);
    effects({0x48,0x89,0x4c,0x24,0x30},false,true);
    effects({0x48,0x89,0x4c,0x24,0x28},true,true);
    // Frame pointers derived in the analysed code are tracked exactly.
    effects({0x48,0x8d,0x44,0x24,0x30,0x48,0x89,0x08},false);           // LEA of the slot, then a store.
    effects({0x48,0x8d,0x44,0x24,0x20,0x48,0x89,0x08},true);            // Below the slot.
    effects({0x48,0x8d,0x44,0x24,0x20,0x48,0x89,0x48,0x10},false);      // Displacement reaches the slot.
    effects({0x48,0x89,0xe0,0x48,0x83,0xc0,0x30,0x48,0x89,0x08},false); // MOV RSP, then ADD.
    effects({0x48,0x8d,0x44,0x24,0x30,0x48,0x31,0xc8,0x48,0x89,0x10},false); // Combined: unknown offset.
    effects({0x48,0x8d,0x44,0x24,0x20,0x48,0x89,0x14,0x08},true);       // Indexed within an object below the slot.
    effects({0x48,0x8d,0x44,0x24,0x30,0x48,0x89,0x14,0x08},false);      // Indexed from the slot.
    // An escaped slot address may return through any load or call result.
    effects({0x48,0x8d,0x44,0x24,0x30,0x48,0x89,0x01,0x49,0x8b,0x10,0x4c,0x89,0x0a},false);
    effects({0x48,0x8d,0x44,0x24,0x20,0x48,0x89,0x01,0x49,0x8b,0x10,0x4c,0x89,0x0a},true);
    effects({0x48,0x8d,0x4c,0x24,0x30,0xe8,0,0,0,0x10,0x49,0x8b,0x10,0x4c,0x89,0x0a},false);
    effects({0x48,0x8d,0x4c,0x24,0x20,0xe8,0,0,0,0x10,0x49,0x8b,0x10,0x4c,0x89,0x0a},true);
    // A call escapes an exact address below the slot; afterwards the register holds it or a
    // callee value, both pointers into escaped objects.
    effects({0x48,0x8d,0x5c,0x24,0x20,0xe8,0,0,0,0x10,0x48,0x89,0x0b},true);
    effects({0x48,0x8d,0x5c,0x24,0x30,0xe8,0,0,0,0x10,0x48,0x89,0x0b},false); // The slot address escapes.
    // Memory-form CMPXCHG leaves RAX unchanged or loaded, never the stored lock-slot address.
    effects({0x48,0x8d,0x4c,0x24,0x20,0xf0,0x49,0x0f,0xb1,0x0a,0x48,0x89,0x10},true);
    effects({0x48,0x8d,0x44,0x24,0x28,0x48,0x8d,0x4c,0x24,0x20,0xf0,0x49,0x0f,0xb1,0x0a,0x48,0x89,0x50,0x08},false);
    // A join feeding a call gives the same result whichever predecessor is analysed first:
    // the escaped lock-slot address on the fall-through or on the branch.
    effects({0x48,0x8d,0x4c,0x24,0x20,0x49,0x89,0x0a,0x75,0x02,0xeb,0x03,
             0x49,0x8b,0x0a,0xe8,0,0,0,0x10,0x48,0x89,0x11},true);
    effects({0x48,0x8d,0x4c,0x24,0x20,0x49,0x89,0x0a,0x75,0x03,
             0x49,0x8b,0x0a,0xe8,0,0,0,0x10,0x48,0x89,0x11},true);
    // Stack-lock recursion check: the lock-slot address escapes into the header, `mark - rsp`
    // goes into the slot and a call follows; a store through a call result keeps the saved slot.
    effects({0x48,0x8d,0x4c,0x24,0x20,0xf0,0x49,0x0f,0xb1,0x0a,0x48,0x29,0xe0,0x48,0x89,0x01,
             0xe8,0,0,0,0x10,0x48,0x89,0x02},true);
    effects({0x48,0x29,0xe0,0x48,0x01,0xe0,0x48,0x89,0x08},false); // RSP added back after the SUB.
    // The lock-slot address, stored into the header, meets a value loaded back on the
    // other path; a store through the joined register keeps the saved slot.
    effects({0x48,0x8d,0x4c,0x24,0x20,0x49,0x89,0x0a,0x75,0x02,0xeb,0x03,
             0x49,0x8b,0x0a,0x48,0x89,0x11},true);
    // It meets an unescaped frame pointer whose path writes the slot through the join.
    effects({0x48,0x8d,0x4c,0x24,0x20,0xf0,0x49,0x0f,0xb1,0x0a,0x75,0x06,
             0x48,0x89,0x51,0x08,0xeb,0x07,
             0x48,0x8d,0x4c,0x24,0x28,0xeb,0xf3},false);
    // An inflated-lock path where the lock slot never escaped meets a slow path's call result:
    // the join keeps the exact address alongside the escaped objects.
    effects({0x48,0x8d,0x4c,0x24,0x20,0x48,0xc7,0x01,3,0,0,0,0x75,0x05,
             0xe8,0,0,0,0x10,0xe8,0,0,0,0x10,0x48,0x89,0x02},true);
    // Its exact part still reaches the slot through a displacement.
    effects({0x48,0x8d,0x4c,0x24,0x28,0x75,0x05,0xe8,0,0,0,0x10,0x48,0x89,0x51,0x08},false);
    // Its escaped part may reach the slot once the slot address escaped.
    effects({0x48,0x8d,0x4c,0x24,0x20,0x75,0x05,0xe8,0,0,0,0x10,
             0x48,0x8d,0x44,0x24,0x30,0x48,0x89,0x44,0x24,0x10,0x48,0x89,0x11},false);
    std::printf("COMPILED_ALIAS_OK checks=%u actualOverwrites=2 rspIndexedInvalidatesSlot=1 derivedPointers=1 escapes=1 nonFramePointersRetained=1 frameDifferences=1 escapedExactJoins=1 cmpxchgRax=1 callJoinOrderIndependent=1 exactOrEscaped=1\n",checks);
}
